void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    BaseType_t xHigherPriorityTaskWoken = pdFALSE;
    if(huart->Instance == USART2)
    {
        if(rxChar == '\r' || rxChar == '\n')
        {
            if(uartIndex > 0)
            {
                uartBuffer[uartIndex] = '\0';
                CommandMessage msg;
                strncpy(msg.text, uartBuffer, CMD_MAX_LEN);

                // Send all user input to menuQueue
                xQueueSendFromISR(menuQueue, &msg, &xHigherPriorityTaskWoken);


                uartIndex = 0;
            }
        }
        else if(uartIndex < CMD_MAX_LEN-1)
        {
            uartBuffer[uartIndex++] = rxChar;
        }

        HAL_UART_Receive_IT(&huart2, (uint8_t*)&rxChar, 1);
        portYIELD_FROM_ISR(xHigherPriorityTaskWoken);
    }
}




